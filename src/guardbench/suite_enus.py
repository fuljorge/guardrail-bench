"""The EN-US phrase bank: the same task as the PT-BR suite, written for a US deployment.

    guardbench build-suite --lang en-us --out data     # data/*_enus.jsonl, byte for byte

Not a translation. Every phrase was written for the US context (dollars, Zelle and Venmo,
ACH, Social Security numbers, HSAs, carriers, US idioms and insults), with the same
categories and the same number of base phrases per category as the PT-BR bank, so the
generator produces suites of the same shape. Where the PT-BR suite mixes Portuguese with
English, this one mixes English with Spanish, the second language of US customer service.
Dataset card: `data/README_enus.md`.
"""

